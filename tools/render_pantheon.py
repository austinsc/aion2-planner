"""Write the Pantheon tab's shared data, and check a class's Pantheon file.

python3 tools/render_pantheon.py

tools/pantheon_base.json      the shared facts: the ten deity stats, the slots, every piece with its points and source,
                              the order to get them and the sources.  -> shared/pantheon.js (const PANTHEON_BASE)
classes/<class>.pantheon.json the class's presets; render.py merges it into <class>-planner/data.js (DATA.pantheon)
                              and checks it with check_class() below.

The tab itself is rendered by shared/planner.js.
"""
import json, os
from urllib.parse import urlparse

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SLOTS = {'colossus': 1, 'statue': 4, 'artwork': 12}


def load_base():
    base = json.load(open(os.path.join(HERE, 'pantheon_base.json'), encoding='utf-8'))
    stats = {s['name'] for s in base['stats']}
    for p in base['pieces']:
        if p['slot'] not in SLOTS:
            raise SystemExit(f"{p['id']}: unknown slot {p['slot']}")
        for st in list(p['stats']) + p.get('either', []):
            if st not in stats:
                raise SystemExit(f"{p['id']}: unknown stat {st}")
    if len({p['id'] for p in base['pieces']}) != len(base['pieces']):
        raise SystemExit('duplicate piece ids')
    return base


def check_class(d, base):
    """Problems in a class's Pantheon file, as (where, what) pairs."""
    bad = []
    stats = {s['name'] for s in base['stats']}
    pieces = {p['id']: p for p in base['pieces']}
    for pr in d.get('presets', []):
        where = f"pantheon {pr.get('name')}"
        if pr.get('mode') not in ('PvE', 'PvP', 'PvE and PvP'):
            bad.append((where, 'mode must be PvE, PvP or "PvE and PvP"'))
        for x in pr.get('priority', []):
            if x.get('stat') not in stats: bad.append((where + ' priority', x.get('stat')))
        for st in pr.get('bracelets', []):
            if st not in stats: bad.append((where + ' bracelets', st))
        if len(pr.get('bracelets', [])) > 8: bad.append((where, 'two bracelets hold 8 lines at most'))
        used = {'colossus': [pr.get('colossus')], 'statue': pr.get('statues', []),
                'artwork': [a['id'] for a in pr.get('artworks', []) for _ in range(a.get('n', 1))]}
        for slot, ids in used.items():
            if len(ids) != SLOTS[slot]:
                bad.append((where, f'{SLOTS[slot]} {slot} slot(s) needed, has {len(ids)}'))
            for i in ids:
                p = pieces.get(i)
                if not p: bad.append((where, f'unknown piece {i}')); continue
                if p['slot'] != slot: bad.append((where, f'{i} is a {p["slot"]}, not a {slot}'))
                pick = pr.get('statueStat') if slot == 'statue' else pr.get('artworkStat')
                if p.get('either') and pick not in p['either']:
                    bad.append((where, f"{i} needs {'statueStat' if slot == 'statue' else 'artworkStat'} of {p['either']}"))
    if not d.get('presets'): bad.append(('pantheon', 'no presets'))
    hosts = {urlparse(x['url']).netloc.replace('www.', '') for x in d.get('sources', []) if x.get('url') and not x.get('region')}
    if len(hosts) < 3:
        bad.append(('pantheon', f'needs sources from at least 3 different sites (not counting region ones), has {sorted(hosts)}'))
    for x in d.get('sources', []):
        if x.get('region') not in (None, 'KR', 'TW'): bad.append(('pantheon source', f"region {x.get('region')!r}"))
    return bad


def main():
    base = load_base()
    out = os.path.join(ROOT, 'shared', 'pantheon.js')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/render_pantheon.py from tools/pantheon_base.json. */\n')
        f.write('const PANTHEON_BASE = ' + json.dumps(base, ensure_ascii=False, indent=1) + ';\n')
    print('shared/pantheon.js', os.path.getsize(out), 'bytes')


if __name__ == '__main__':
    main()
