"""Write the Stones tab data.

python3 tools/render_stones.py [class ...]

tools/stones_base.json   the shared facts: all 51 Theostones with exact tooltips, the Manastone slot, size and stat tables,
                         the odds calculator inputs, general rules, levelling advice, caveats and sources.
                         -> shared/stones.js (const STONES)
classes/<class>.stones.json   the written advice for one class: Manastone priority, Theostone picks and what the top
                         players of that class run.
                         -> <class>-planner/stones.js (DATA.stones)

The Stones tab itself is rendered by shared/planner.js. Stone icons are in shared/stone-icons/ and come from Metabot.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def load_base():
    base = json.load(open(os.path.join(HERE, 'stones_base.json'), encoding='utf-8'))
    keys = {e['k'] for e in base['effects']}
    names = {g['name']: e['k'] for e in base['effects'] for g in e['grades'].values()}
    icons = set(os.listdir(os.path.join(ROOT, 'shared', 'stone-icons')))
    for e in base['effects']:
        if e['icon'] + '.webp' not in icons:
            raise SystemExit(f"missing icon {e['icon']}")
    for group in base['stoneIcons'].values():
        for f in group:
            if f + '.webp' not in icons:
                raise SystemExit(f'missing icon {f}')
    return base, keys, names


def check_class(cls, d, keys, names):
    bad = []
    for sect in ('pve', 'pvp', 'alt'):
        for k in d['theo'].get(sect, {}).get('effects', []):
            if k not in keys:
                bad.append((sect, k))
    for n, share in d['theo']['top']:
        if n not in names:
            bad.append(('top', n))
    if bad:
        raise SystemExit(f'{cls}: unknown stone names or effects {bad}')


def main():
    base, keys, names = load_base()
    out = os.path.join(ROOT, 'shared', 'stones.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by tools/render_stones.py from tools/stones_base.json. */\n')
        f.write('const STONES = ' + json.dumps(base, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('shared/stones.js', os.path.getsize(out), 'bytes')
    wanted = sys.argv[1:]
    for fn in sorted(os.listdir(os.path.join(ROOT, 'classes'))):
        if not fn.endswith('.stones.json'):
            continue
        cls = fn.split('.')[0]
        if wanted and cls not in wanted:
            continue
        d = json.load(open(os.path.join(ROOT, 'classes', fn), encoding='utf-8'))
        check_class(cls, d, keys, names)
        p = os.path.join(ROOT, f'{cls}-planner', 'stones.js')
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(f'/* Generated by tools/render_stones.py from classes/{cls}.stones.json. */\n')
            f.write('DATA.stones = ' + json.dumps(d, ensure_ascii=False, separators=(',', ':')) + ';\n')
        print(cls, os.path.getsize(p), 'bytes')


if __name__ == '__main__':
    main()
